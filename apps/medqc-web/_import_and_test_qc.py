def import_to_pg():
    """将两份完整病历导入 PG 的 admission_record 表（record_content 列）"""
    engine = sa.create_engine(DB_URL)
    
    cases = [
        {
            'institute_id': 'SCPH',
            'patient_id': 'P-ZS-2026',
            'visit_id': 'V-ZS-001',
            'name': '张三',
            'sex': '男',
            'age_year': 58,
            'dept_name': '心血管内科',
            'admission_datetime': '2026-01-01 09:30:00',
            'bed_no': '15',
            'chief_complaint': '反复胸闷、心悸3年，加重伴胸痛1周',
            'record_content': CASE_1_ZHANGSAN,
        },
        {
            'institute_id': 'LZZXYY',
            'patient_id': 'P-LM-2025',
            'visit_id': 'V-LM-001',
            'name': '李明',
            'sex': '男',
            'age_year': 35,
            'dept_name': '外二科（肛肠外科）',
            'admission_datetime': '2025-03-29 13:49:00',
            'bed_no': '08',
            'chief_complaint': '发现肛旁肿物伴疼痛2天',
            'record_content': CASE_2_LIMING,
        },
    ]
    
    with engine.connect() as conn:
        for case in cases:
            # 先删除可能存在的旧数据
            conn.execute(sa.text(
                "DELETE FROM admission_record WHERE patient_id = :pid AND visit_id = :vid"
            ), {'pid': case['patient_id'], 'vid': case['visit_id']})
            
            conn.execute(sa.text("""
                INSERT INTO admission_record 
                (institute_id, patient_id, visit_id, name, sex, age_year, 
                 dept_name, admission_datetime, bed_no, chief_complaint, record_content)
                VALUES (:institute_id, :patient_id, :visit_id, :name, :sex, :age_year,
                        :dept_name, :admission_datetime, :bed_no, :chief_complaint, :record_content)
            """), case)
            
            print(f"  ✅ {case['name']}({case['patient_id']}) — {len(case['record_content'])} 字")
        
        conn.commit()
    
    print(f"\n已导入 {len(cases)} 条记录到 admission_record 表")
    return cases


