API_BASE = 'http://localhost:8001'

def test_qc_for_case(case_name: str, content: str, document_type: str = "入院记录"):
    """
    调用 /api/v1/qc/sichuan/evaluate 走分段 Pipeline
    
    SegmentedQCPipeline 自动完成：
      1. document_segmenter 切段
      2. rule_router 匹配规则
      3. 分批(≤15条/批) 并发 LLM
      4. 结果合并去重
    """
    print(f"\n{'='*80}")
    print(f"  质控测试：{case_name}")
    print(f"  文本长度：{len(content)} 字符")
    print(f"  Pipeline：SegmentedQCPipeline（自动切段+分批+并发LLM）")
    print(f"{'='*80}")
    
    payload = {
        "document_id": f"test-{case_name}",
        "document_content": content,
        "document_type": document_type,
        "persist": True,           # 保存结果
        "prompt_mode": "plan_a",   # 使用方案A（提取检查要点）
    }
    
    print(f"\n⏳ 正在调用 QC API（可能需要 30-120 秒）...")
    start = time.time()
    
    try:
        resp = requests.post(
            f"{API_BASE}/api/v1/qc/sichuan/evaluate",
            json=payload,
            timeout=300
        )
        elapsed = time.time() - start
        
        print(f"   响应状态码：{resp.status_code}（耗时 {elapsed:.1f}s）")
        
        if resp.status_code != 200:
            print(f"   ❌ 失败：{resp.text[:500]}")
            return None
        
        result = resp.json()
        
        # 打印结果
        summary = result.get('evaluation_summary', {})
        perf = result.get('performance_metrics', {})
        eval_results = result.get('evaluation_results', [])
        sections = result.get('sections_summary', [])
        
        print(f"\n📊 质控结果摘要：")
        print(f"   模式：{result.get('mode', 'N/A')}")
        print(f"   使用模型：{summary.get('model', 'N/A')}")
        print(f"   总规则数：{summary.get('total_rules', 0)}")
        print(f"   合规数：{summary.get('compliant_rules', 0)}")
        print(f"   问题数：{summary.get('issues_found', 0)}")
        print(f"   合规率：{summary.get('compliance_rate', 0):.1f}%")
        print(f"   综合等级：{summary.get('overall_grade', 'N/A')}")
        
        if sections:
            print(f"\n📄 段落切割结果（{len(sections)} 段）：")
            for i, sec in enumerate(sections, 1):
                print(f"   {i}. [{sec.get('type')}] {sec.get('title', '')} — {sec.get('chars', 0)}字")
        
        print(f"\n⏱️  性能指标：")
        print(f"   Pipeline 耗时：{perf.get('pipeline_time', 0):.1f}s")
        print(f"   LLM 调用次数：{perf.get('llm_calls', 0)}")
        print(f"   Token 消耗：{perf.get('token_usage', 0)}")
        print(f"   API 耗时：{perf.get('api_time', 0):.1f}s")
        estimated_cost = perf.get('token_usage', 0) / 1000 * 0.002
        print(f"   预估成本：¥{estimated_cost:.4f}")
        
        # 显示不合规项
        non_compliant = [r for r in eval_results if not r.get('is_compliant', True)]
        if non_compliant:
            print(f"\n❌ 不合规项（{len(non_compliant)} 条）：")
            for i, item in enumerate(non_compliant[:10], 1):
                print(f"\n   {i}. [{item.get('rule_id', 'N/A')}] {item.get('rule_name', 'N/A')}")
                findings = item.get('findings', '')
                if findings:
                    print(f"      发现：{findings[:150]}...")
                suggestion = item.get('suggestion', '')
                if suggestion:
                    print(f"      建议：{suggestion[:150]}...")
                confidence = item.get('confidence', 0)
                print(f"      置信度：{confidence}")
            if len(non_compliant) > 10:
                print(f"   ... 还有 {len(non_compliant) - 10} 条")
        else:
            print(f"\n✅ 所有规则均合规")
        
        return result
        
    except requests.exceptions.Timeout:
        print(f"   ❌ 超时（300s）")
        return None
    except Exception as e:
        print(f"   ❌ 异常：{e}")
        import traceback
        traceback.print_exc()
        return None


