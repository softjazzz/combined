# 06-01-05：CT/MRI 异常是否有病程医师自己的分析。
EXAM_FINDING_ANALYSIS_EXAMPLES = (
    "判定例子（合成文本，只说明口径）："
    "①“复查胸部CT：双肺下叶少许渗出，较前片病灶减少。患者目前CT提示较前好转。查体：双肺未闻及干湿啰音。”"
    "→不算分析：复述报告、笼统“较前好转”加正常查体，没有医师自己的判断；"
    "对照“复查胸部CT双肺下叶渗出较前减少，结合体温已正常、咳痰减少，考虑肺部感染控制有效，继续原抗感染方案3天后复评”"
    "→算分析：把影像变化与症状联系并作出判断、据此定计划。"
    "②“诊断依据：头颅CT示右侧基底节区脑出血，故诊断。”→不算：只把报告所见抄进依据再接故诊断；"
    "对照“突发左侧肢体无力伴意识障碍，查体左侧肌力2级，头颅CT示右侧基底节区出血，症状体征与病灶部位相符，故诊断”"
    "→算：写出症状体征与病灶部位的对应关系。"
    "③“腰椎MRI示L4/5椎间盘突出，拟行理疗。”→不算：只有异常加拟处置，没有依据；"
    "对照“L4/5椎间盘突出压迫右侧神经根，与右下肢放射痛相符，予理疗及甘露醇脱水”→算。"
    "④“胸部CT：右肺上叶病灶较前吸收。另：proBNP 5281pg/ml。”→不算：旁列与该影像异常无关的检验数值不是对该异常的分析。"
    "⑤膝关节MRI诊断依据写“膝痛、关节间隙压痛、结合MR可诊断”，同一病程另有腰椎MRI椎间盘突出→对腰椎异常不算分析。"
    "⑥“结合今日MRI，修正诊断为右侧额顶叶新近脑梗死，加用阿司匹林抗血小板”→算：报告后修正诊断并据此处置。"
)

