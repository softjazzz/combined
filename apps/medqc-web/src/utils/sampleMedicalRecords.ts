/**
 * 根据病历类型获取示例病历
 */
export function getSampleRecordsByType(type: string): SampleMedicalRecord[] {
  return SAMPLE_MEDICAL_RECORDS.filter(record => record.type === type)
}

/**
 * 根据ID获取示例病历
 */
export function getSampleRecordById(id: string): SampleMedicalRecord | undefined {
  return SAMPLE_MEDICAL_RECORDS.find(record => record.id === id)
}

/**
 * 获取所有示例病历
 */
export function getAllSampleRecords(): SampleMedicalRecord[] {
  return SAMPLE_MEDICAL_RECORDS
}

