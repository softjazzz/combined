INSTITUTE_ID = "LX001"  # 泸县医院机构号


def seed():
    """插入测试数据"""
    with get_db_context() as db:
        # 先清空旧数据
        db.execute(text("DELETE FROM diagnosis"))
        db.execute(text("DELETE FROM mr"))
        db.execute(text("DELETE FROM admission_record"))
        print("🧹 已清空旧测试数据")

        for i, r in enumerate(TEST_RECORDS):
            pid, vid, name, sex, age, bed, dept, ins, adm_str, dis_str, days, doc, diag_name, diag_code = r
            adm_dt = datetime.strptime(adm_str, "%Y-%m-%d")
            dis_dt = datetime.strptime(dis_str, "%Y-%m-%d")
            mr_no = f"BA2026{i+1:04d}"

            # 1. 病案首页
            mr = MedicalRecordFrontpage(
                institute_id=INSTITUTE_ID,
                patient_id=pid,
                visit_id=vid,
                name=name,
                sex=sex,
                age_year=age,
                mr_no=mr_no,
                inpat_no=f"ZY2026{i+1:04d}",
                insurance_type=ins,
                admission_dept_name=dept,
                discharge_dept_name=dept,
                admission_datetime=adm_dt,
                discharge_datetime=dis_dt,
                hospital_duration=days,
                attending_physician_sign=doc,
            )
            db.add(mr)

            # 2. 诊断（出院主要诊断）
            diag = Diagnosis(
                institute_id=INSTITUTE_ID,
                patient_id=pid,
                visit_id=vid,
                diagnosis_id=f"D{i+1:04d}-01",
                name=name,
                sex=sex,
                dept_name=dept,
                diagnosis_type="出院主要诊断",
                diagnosis_no="1",
                diagnosis_name=diag_name,
                diagnosis_code=diag_code,
            )
            db.add(diag)

            # 3. 入院记录（提供床号）
            adm = AdmissionRecord(
                institute_id=INSTITUTE_ID,
                patient_id=pid,
                visit_id=vid,
                name=name,
                sex=sex,
                age_year=age,
                bed_no=bed,
                dept_name=dept,
                admission_datetime=adm_dt,
            )
            db.add(adm)

        print(f"✅ 插入 {len(TEST_RECORDS)} 条测试病历（9 个科室）")
        print("   表: mr（病案首页）、diagnosis（诊断）、admission_record（入院记录）")


if __name__ == "__main__":
    seed()
