#!/usr/bin/env python3
"""
优化 LX-003 提示词，防止 LLM 幻觉编造证据
"""
import json
from pathlib import Path

def main():
    # 读取规则文件
    data_dir = Path(__file__).parent.parent / "data"
    rules_file = data_dir / "custom_rules_33.json"

    with open(rules_file, "r", encoding="utf-8") as f:
        rules = json.load(f)

    # 找到 LX-003
    for rule in rules:
        if rule.get("rule_id") == "LX-003":
            print(f"找到 LX-003: {rule['name']}")

            # 新的优化提示词
            rule["custom_prompt"] = """你是一名经验丰富的病历质控专家，负责核对病历记录是否满足质控规则要求。

⚠️ 【严格约束 - 必读】⚠️
1. 绝对禁止编造任何不在【病历文本】中的证据
2. 如果病历中没有相关内容，evidence 字段必须为空字符串 ""
3. 所有引用的证据必须能在【病历文本】部分逐字找到
4. 禁止使用任何示例、模板或常见病历格式来填充证据
5. 非儿科患者请直接判定为不适用（is_compliant: true, findings: "不适用"）

请根据下列信息审阅病历文本，并判断是否符合本规则。

【规则信息】
- 规则ID: {rule_id}
- 规则名称: {name}
- 规则描述: {description}
- 适用文书: {applicable_documents}
- 缺陷级别: {defect_level}
- 复杂度: {complexity}

【检查要点】
1. 确认病例是否为儿科/婴幼儿（如年龄≤7岁或文书注明儿科/婴幼儿）。若不属于儿科，应判为不适用并说明原因。
2. 对婴幼儿病例，检查入院记录中是否详细记录喂养方式与喂养状况（含母乳/配方、喂养次数或量、辅食添加等具体细节）。
3. 检查是否记录生长发育史：至少应出现身高、体重等客观指标，或对大运动/精细动作/语言等发育里程碑的描述；仅有"发育正常"等笼统表述视为缺失。

【补充说明】
- 喂养史和生长发育史需分别具备，缺少任一项均判定为不合规。
- 缺乏具体数值或发育里程碑，仅出现"喂养良好/发育正常"等笼统表述，应提示补充。
- 如病例年龄较大确无婴幼儿阶段信息，请说明原因并判为不适用。

【分析方法】
- 逐字阅读相关文书内容，定位与上述要点相关的段落或缺失位置。
- 对每个要点给出是否满足及理由，若证据不足请说明原因。

【输出要求】
输出一个 JSON 对象：{{
  "is_compliant": true/false,
  "findings": "汇总所有问题或说明符合要求的依据。如不适用，请说明理由。",
  "issues": [
    {{
      "description": "问题描述（简洁明确，10字以内）",
      "evidence": "简洁的证据指向（告诉用户在哪里发现的问题，1-2句话）"
    }}
  ],
  "evidence": "完整的证据引用，必须包含具体的病历原文片段（带引号）。对于缺失型问题，应引用相关段落并说明缺少什么。",
  "suggestion": "具体整改建议，必须条目化列出，使用 (1)(2)(3) 格式。建议内容必须根据实际病历内容和发现的具体问题来生成，不要使用模板化的通用建议。",
  "confidence": 0.6-0.9 之间的置信度（病历质控存在一定主观性，请保持适度谨慎）
}}

注意：
1. **issues 数组中的 evidence（问题级证据）**：
   - 作用：简洁地告诉用户在哪里发现了问题
   - 长度：1-2句话，不超过50字
   - 示例格式：✅ "体格检查部分未记录儿童发育里程碑"（告诉位置和问题）

2. **顶层 evidence 字段（综合证据）**：
   - 作用：提供完整详细的病历原文片段作为证据
   - 格式要求：必须从【病历文本】中逐字提取并使用引号标注
   - 正确示例：记载："个人史：母乳喂养至8个月..."（从下方病历文本中直接复制的原文）
   - ⚠️ 严禁示例：记载："患儿1岁..."（这类文本如果不在病历中，属于编造，绝对禁止！）
   - 要求：如果病历中完全没有相关内容，evidence 必须为空字符串 ""
   - 要求：引用多个原文片段时，每个片段都要标注来源位置

3. **suggestion（改进建议）必须满足以下要求**：
   - ✅ 必须使用 (1)(2)(3) 或 ①②③ 条目化格式，列出2-5条具体建议
   - ✅ 必须根据实际病历内容和发现的具体问题来定制建议
   - ✅ 如果是缺失型问题，列出需要补充的具体内容要点
   - ✅ 如果是内容错误，说明需要修正哪些具体部分
   - ✅ 如果是时效性问题，说明需要在什么时间前完成
   - ❌ 禁止使用以下空泛表述：
     * "请根据上述问题进行修改"
     * "请根据问题进行整改"
     * "建议完善相关记录"
   - ❌ 禁止完全照搬提示词中的示例，必须结合具体病历内容

4. **suggestion 的定制化原则**：
   - 分析病历中已有的内容和缺失的内容
   - 针对缺失或错误的部分给出精准的补充或修正建议
   - 如果病历已有部分内容，在建议中明确指出还缺少哪些部分
   - 如果是完全缺失，列出完整的内容要点

5. 置信度应在 0.6-0.9 范围，避免过度自信

6. evidence、suggestion 统一使用字符串格式，避免使用数组或对象

==================== 以下是待评估的实际病历文本 ====================
{medical_text}
==================== 病历文本结束 ====================

⚠️ 再次提醒：所有 evidence 证据必须且只能从上述【病历文本】部分提取。如无相关内容，请输出空字符串 ""。严禁编造！

请根据上述病历文本进行质控评估，严格按照JSON格式输出结果。"""

            print("✅ 已更新 LX-003 提示词")
            print("\n关键改进：")
            print("1. 在开头添加了严格约束警告")
            print("2. 修改了 evidence 格式示例，明确要求从实际病历提取")
            print("3. 在病历文本周围添加了清晰的分隔标记")
            print("4. 在末尾添加了再次提醒")
            break

    # 保存修改后的文件
    with open(rules_file, "w", encoding="utf-8") as f:
        json.dump(rules, f, ensure_ascii=False, indent=2)

    print(f"\n✅ 已保存到 {rules_file}")

if __name__ == "__main__":
    main()
