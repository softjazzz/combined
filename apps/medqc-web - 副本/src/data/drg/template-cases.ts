const ACTUAL_COST_FIELDS = [
  'total_cost',
  'drug_fee',
  'material_fee',
  'exam_fee',
  'treatment_fee',
  'surgery_fee',
  'bed_fee',
  'nursing_fee',
  'other_fee',
] as const

const PAYMENT_FIELDS = ['baseline_payment', 'insurance_payment'] as const

const DEPARTMENT_COST_FACTORS: Record<string, number> = {
  呼吸内科专业: 0.98,
  心血管内科专业: 1.08,
  普通外科专业: 1.14,
  骨科专业: 1.2,
  儿科: 0.86,
  神经内科专业: 1.04,
}

function formatDate(date: Date): string {
  return date.toISOString().slice(0, 10)
}

function shiftDate(base: Date, days: number): Date {
  const next = new Date(base)
  next.setUTCDate(next.getUTCDate() + days)
  return next
}

function scaleMoney(value: number | undefined, factor: number): number | undefined {
  if (typeof value !== 'number') return undefined
  return Math.max(0, Math.round(value * factor))
}

function buildGeneratedAdmissionId(index: number, dischargeDate: Date): string {
  const yearMonth = formatDate(dischargeDate).slice(0, 7).replace('-', '')
  return `${yearMonth}-${String(index + 1).padStart(5, '0')}`
}

/**
 * 生成模板下载用样例数据。
 *
 * 保留种子病例的科室、诊断、手术、分组和费用结构，按顺序扩展出 2000 条
 * 唯一住院号的病例，便于事中监控、付费监测、事后分析共用同一份大样本模板。
 */
export function buildTemplateCases(count = TEMPLATE_DOWNLOAD_RECORD_COUNT): CaseRecord[] {
  const startDate = new Date(Date.UTC(2025, 0, 1))

  return Array.from({ length: count }, (_, index) => {
    const source = templateCases[index % templateCases.length]
    const los = source.los ?? 5
    const dischargeDate = shiftDate(startDate, index % 365)
    const admissionDate = shiftDate(dischargeDate, -los)
    const baseFactor = 0.88 + ((index * 17) % 27) / 100
    const departmentCostFactor = DEPARTMENT_COST_FACTORS[source.department] ?? 1
    const actualCostFactor = baseFactor * departmentCostFactor
    const paymentFactor = baseFactor * (0.98 + ((index * 7) % 9) / 100)
    const record: CaseRecord = {
      ...source,
      admission_id: buildGeneratedAdmissionId(index, dischargeDate),
      patient_name: `${source.patient_name}${Math.floor(index / templateCases.length) + 1}`,
      age:
        typeof source.age === 'number'
          ? Math.max(1, Math.min(98, source.age + ((index % 9) - 4)))
          : source.age,
      admission_date: formatDate(admissionDate),
      discharge_date: formatDate(dischargeDate),
      los,
    }

    for (const field of ACTUAL_COST_FIELDS) {
      const scaledValue = scaleMoney(source[field], actualCostFactor)
      if (typeof scaledValue === 'number') {
        record[field] = scaledValue
      }
    }

    for (const field of PAYMENT_FIELDS) {
      const scaledValue = scaleMoney(source[field], paymentFactor)
      if (typeof scaledValue === 'number') {
        record[field] = scaledValue
      }
    }

    return record
  })
}
