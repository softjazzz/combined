/**
 * 获取内置测试用例
 * 优先尝试后端 API，失败时返回本地内嵌数据
 */
export async function fetchTestCases(): Promise<TestCase[]> {
  try {
    const resp = await fetch('/api/v1/test-cases')
    if (resp.ok) {
      const json = await resp.json()
      if (json.data?.length > 0) {
        return json.data.map((item: any) => ({
          name: item.name || item.title || '未命名病历',
          description: item.description || '',
          medical_text: item.medical_text || '',
        }))
      }
    }
  } catch {
    // 后端不可用，使用本地数据
  }
  return getBuiltinTestCases()
}

